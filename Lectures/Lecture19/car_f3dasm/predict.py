"""Degree-2 polynomial surrogate for the car stopping distance y(x).

Loads the ExperimentData in data/ (generated by generate_data.py), fits a
degree-2 polynomial with scikit-learn, and exposes predict(x).
"""

from pathlib import Path

import numpy as np
from f3dasm import ExperimentData
from sklearn.linear_model import LinearRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import PolynomialFeatures

DATA_DIR = Path(__file__).resolve().parent / "data"


def _fit_model():
    data = ExperimentData.from_file(DATA_DIR)
    input_df, output_df = data.to_pandas()
    x = input_df[["x"]].to_numpy(dtype=float)
    y = output_df["y"].to_numpy(dtype=float)
    model = make_pipeline(PolynomialFeatures(degree=2), LinearRegression())
    model.fit(x, y)
    return model


_MODEL = _fit_model()


def predict(x):
    """Predicted stopping distance y (m) for speed x (m/s).

    Accepts a scalar or array-like of speeds; returns a float for a scalar
    input and an array of the same length otherwise.
    """
    x_arr = np.atleast_1d(np.asarray(x, dtype=float))
    y_hat = _MODEL.predict(x_arr.reshape(-1, 1))
    if np.ndim(x) == 0:
        return float(y_hat[0])
    return y_hat
